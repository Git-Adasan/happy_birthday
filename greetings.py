def make_greeting(full_name: str, age: int, style: str, idx: int):
    """Вернуть (текст, нормализованный индекс)."""
    variants = STYLES[style][1]
    if age is None:  # год рождения неизвестен — берём варианты без возраста
        variants = [v for v in variants if "{years}" not in v]
    idx %= len(variants)
    text = variants[idx].format(
        name=first_name(full_name), years=years_text(age) if age is not None else ""
    )
    return text, idx
